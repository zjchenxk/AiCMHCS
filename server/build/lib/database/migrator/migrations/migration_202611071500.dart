/// v7 数据订正：ROLE_CODE 角色原值搬迁至 USER_TYPE，并按角色回填权限级别。
///
/// 幂等：仅处理 USER_TYPE / PERMISSION_LEVEL 仍为 NULL 的行，中断重跑不会
/// 重复处理；TEACHER / PARENT 不在新值域内，按约定原值保留待人工订正。
Future<void> migrateRoleToUserType(
  DatabaseGateway db,
  FieldCipher cipher,
) async {
  await db.execute(
    'UPDATE SYS_USER SET USER_TYPE = ROLE_CODE '
    'WHERE USER_TYPE IS NULL AND ROLE_CODE IS NOT NULL',
  );
  await db.execute(
    'UPDATE SYS_USER SET PERMISSION_LEVEL = '
    "CASE WHEN USER_TYPE = 'ADMIN' THEN 2 "
    "WHEN USER_TYPE = 'DOCTOR' THEN 1 ELSE 0 END "
    'WHERE PERMISSION_LEVEL IS NULL',
  );
}
