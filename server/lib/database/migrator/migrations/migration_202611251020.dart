/// v30 数据订正：存量转诊行回填 DATA_SRC_ID 溯源。
///
/// 幂等：哨兵行按「CHILD_ID + REFL_DATE = ASD.CHECK_DATE + HOSP_ID」
/// 反查初筛记录回填真实 ID；查不到的行保持哨兵值（历史脏数据无法溯源，
/// 不强行臆造）。中断重跑对已回填行不再改动。
Future<void> backfillReferralDataSrc(DatabaseGateway db, FieldCipher cipher) async {
  final rows = await db.query(
    'SELECT ID, CHILD_ID, REFL_DATE, HOSP_ID FROM CHILD_REFERRAL '
    "WHERE DATA_SRC_ID = '00000000-0000-0000-0000-000000000000'",
  );
  for (final row in rows.rowsAsMaps) {
    final matched = await db.query(
      'SELECT ID FROM ASD_INITIAL_SCREENING '
      'WHERE CHILD_ID = ? AND CHECK_DATE = ? AND HOSP_ID = ?',
      [row['CHILD_ID'], row['REFL_DATE'], row['HOSP_ID']],
    );
    final sourceId = matched.rows.isEmpty ? row['ID'] : (matched.rowsAsMaps.first['ID'] ?? row['ID']);
    await db.execute('UPDATE CHILD_REFERRAL SET DATA_SRC_ID = ? WHERE ID = ?', [sourceId, row['ID']]);
  }
}
