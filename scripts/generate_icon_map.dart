// 图标映射生成脚本：扫描 Flutter SDK material 库 icons.dart 的全部
// static const IconData 声明，重新生成 client/lib/utils/icon_map_helper.dart。
//
// 收录规则：默认图标全量 + outlined 系列变体（与功能菜单图标统一使用
// outlined 系列的前端约定一致，见 AGENTS.md「UI 风格设定」）；
// rounded/sharp/filled 变体不收录，避免图标选择面板同名图标成倍膨胀。
//
// 运行（仓库根目录执行）：dart run scripts/generate_icon_map.dart
// 可选位置参数指定 Flutter SDK 根目录；缺省依次取环境变量 FLUTTER_ROOT、
// 根 .dart_tool/package_config.json 的 flutter 包 rootUri 反推。
import 'dart:convert';
import 'dart:io';

void main(List<String> args) {
  var sdkRoot = args.isNotEmpty
      ? args[0]
      : Platform.environment['FLUTTER_ROOT'];
  sdkRoot ??= _sdkRootFromPackageConfig();
  sdkRoot = _normalizePath(sdkRoot);

  final iconsFile = File(
    '$sdkRoot/packages/flutter/lib/src/material/icons.dart',
  );
  if (!iconsFile.existsSync()) {
    stderr.writeln('未找到 SDK 图标源文件：${iconsFile.path}');
    stderr.writeln('可用位置参数或 FLUTTER_ROOT 指定 Flutter SDK 根目录。');
    exit(1);
  }

  // 提取全部 IconData 常量名，过滤不收录的变体后缀，按名称排序
  final pattern = RegExp(r'static const IconData\s+(\w+)\s*=');
  final names =
      pattern
          .allMatches(iconsFile.readAsStringSync())
          .map((m) => m.group(1)!)
          .where(
            (n) =>
                !n.endsWith('_rounded') &&
                !n.endsWith('_sharp') &&
                !n.endsWith('_filled'),
          )
          .toSet()
          .toList()
        ..sort();

  final outlinedCount = names.where((n) => n.endsWith('_outlined')).length;
  final outFile = File('client/lib/utils/icon_map_helper.dart');
  outFile.writeAsStringSync(_render(names));
  stdout.writeln('已生成 ${outFile.path}');
  stdout.writeln(
    '共 ${names.length} 个图标（默认 ${names.length - outlinedCount} + outlined $outlinedCount）',
  );
}

/// 从根 package_config.json 的 flutter 包 rootUri 反推 SDK 根目录。
String _sdkRootFromPackageConfig() {
  final configFile = File('.dart_tool/package_config.json');
  if (!configFile.existsSync()) {
    stderr.writeln(
      '找不到 .dart_tool/package_config.json（需先在仓库根执行 flutter pub get），',
    );
    stderr.writeln('或用位置参数 / 环境变量 FLUTTER_ROOT 指定 SDK 根目录。');
    exit(1);
  }
  final config =
      jsonDecode(configFile.readAsStringSync()) as Map<String, dynamic>;
  final packages = (config['packages'] as List).cast<Map<String, dynamic>>();
  final flutter = packages.firstWhere(
    (p) => p['name'] == 'flutter',
    orElse: () => throw StateError('package_config.json 中无 flutter 包'),
  );
  // rootUri 相对路径按配置文件所在目录解析
  var uri = Uri.parse(flutter['rootUri'] as String);
  if (!uri.isAbsolute) uri = configFile.parent.uri.resolveUri(uri);
  return uri.toFilePath(windows: Platform.isWindows);
}

/// 规范化路径：去尾部分隔符，兼容正反斜杠。
String _normalizePath(String path) {
  var p = path.replaceAll('\\', '/');
  while (p.endsWith('/')) {
    p = p.substring(0, p.length - 1);
  }
  return p;
}

/// 渲染生成文件全文（图标映射 + 存量查询 helper 原样保留）。
String _render(List<String> names) {
  final buf = StringBuffer();
  buf.writeln('// GENERATED FILE - DO NOT EDIT');
  buf.writeln('// Generated by scripts/generate_icon_map.dart');
  buf.writeln('// 重新生成（仓库根目录执行）：dart run scripts/generate_icon_map.dart');
  buf.writeln("import 'package:material_ui/material_ui.dart';");
  buf.writeln();
  buf.writeln('/// 图标名 → IconData 全量映射（默认图标 + outlined 系列变体，与功能');
  buf.writeln('/// 菜单 outlined 图标约定一致；不含 rounded/sharp/filled 变体），');
  buf.writeln('/// 按名称排序，供菜单图标选择与解析共用。');
  buf.writeln('const Map<String, IconData> iconMap = {');
  for (final name in names) {
    buf.writeln("  '$name': Icons.$name,");
  }
  buf.writeln('};');
  buf.writeln();
  buf.writeln('IconData? iconFromName(String name) {');
  buf.writeln('  if (name.isEmpty) return null;');
  buf.writeln('  // 尝试直接返回，忽略大小写差异');
  buf.writeln('  final key = name.trim();');
  buf.writeln('  if (iconMap.containsKey(key)) return iconMap[key];');
  buf.writeln('  final low = key.toLowerCase();');
  buf.writeln('  if (iconMap.containsKey(low)) return iconMap[low];');
  buf.writeln('  return null;');
  buf.writeln('}');
  buf.writeln();
  buf.writeln(
    'IconData iconFromNameOrFallback(String name, {IconData fallback = Icons.help}) {',
  );
  buf.writeln('  if (name.isEmpty) return fallback;');
  buf.writeln('  // 尝试直接返回，忽略大小写差异');
  buf.writeln('  final key = name.trim();');
  buf.writeln('  if (iconMap.containsKey(key)) return iconMap[key]!;');
  buf.writeln('  final low = key.toLowerCase();');
  buf.writeln('  if (iconMap.containsKey(low)) return iconMap[low]!;');
  buf.writeln('  return fallback;');
  buf.writeln('}');
  return buf.toString();
}
